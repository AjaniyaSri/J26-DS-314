"""Load C4's *already extracted* static environmental vectors (Notebook 05).

Place at: J26-DS-314/c4_fusion/src/environment/load.py

Inputs (generated by Notebook 05, kept local/private):
    data/processed/c4/environment/c4_environment_features_40_PRIVATE.csv
    data/processed/c4/environment/c4_environment_QA_40_PRIVATE.csv
    data/processed/c4/environment/c4_environment_manifest_PRIVATE.json

No Earth Engine, GeoPandas, HydroRIVERS or raster processing is performed here.
The output is a fixed-order, *unscaled* nine-dimensional vector per station.
Scaling, if needed, must be fitted on training records only (not here).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd


FEATURE_COLUMNS: tuple[str, ...] = (
    "env_log1p_area_km2",
    "env_mean_elevation_m",
    "env_mean_slope_deg",
    "env_tree_fraction",
    "env_cropland_fraction",
    "env_built_fraction",
    "env_worldcover_water_fraction",
    "env_jrc_persistent_water_fraction",
    "env_hydrorivers_density_km_per_km2",
)

FRACTION_COLUMNS: tuple[str, ...] = (
    "env_tree_fraction",
    "env_cropland_fraction",
    "env_built_fraction",
    "env_worldcover_water_fraction",
    "env_jrc_persistent_water_fraction",
)

EXPECTED_STATIONS = 40
EXPECTED_VERSION = "C4_ENV_PILOT_V2_JRC_FULL_POLYGON"
FEATURE_FILENAME = "c4_environment_features_40_PRIVATE.csv"
QA_FILENAME = "c4_environment_QA_40_PRIVATE.csv"
MANIFEST_FILENAME = "c4_environment_manifest_PRIVATE.json"


class EnvironmentDataError(ValueError):
    """The saved environmental data or its provenance failed validation."""


def _repo_root_from_file() -> Path:
    # .../J26-DS-314/c4_fusion/src/environment/load.py -> J26-DS-314
    root = Path(__file__).resolve().parents[3]
    if not (root / "c4_fusion").is_dir():
        raise FileNotFoundError(
            "Cannot determine repository root from load.py. "
            "Pass repo_root=Path('.../J26-DS-314') or data_dir=... explicitly."
        )
    return root


def _read_csv(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing Notebook 05 output: {path}. "
            "Run Notebook 05 Cell 10 and keep its exported files together."
        )
    return pd.read_csv(path, dtype={"station_id": "string"}, low_memory=False)


def _check_ids(df: pd.DataFrame, name: str) -> None:
    if "station_id" not in df.columns:
        raise EnvironmentDataError(f"{name}: missing station_id column")
    if df["station_id"].isna().any() or df["station_id"].str.strip().eq("").any():
        raise EnvironmentDataError(f"{name}: empty station_id")
    if df["station_id"].duplicated().any():
        duplicates = df.loc[df["station_id"].duplicated(keep=False), "station_id"].tolist()
        raise EnvironmentDataError(f"{name}: duplicate station_id values: {duplicates[:8]}")
    if len(df) != EXPECTED_STATIONS:
        raise EnvironmentDataError(f"{name}: expected {EXPECTED_STATIONS} stations, got {len(df)}")


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for piece in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(piece)
    return digest.hexdigest()


class EnvironmentFeatureLoader:
    """Read and validate a frozen Notebook 05 environment dataset *once*.

    Parameters
    ----------
    repo_root:
        Project root (folder containing c4_fusion/ and data/). Usually inferred.
    data_dir:
        Optional explicit directory containing Notebook 05's three exports.
    verify_provenance:
        Require the QA CSV and manifest, and cross-check their station IDs,
        polygon SHA256 values, feature names, and feature version.
    verify_polygon_files:
        Additionally recompute SHA256 for all 40 source polygons on disk.
        Useful before a final experiment; not required for a quick Notebook 06 load.

    Every vector is [9] in FEATURE_COLUMNS order, dtype numpy.float32.
    """

    def __init__(
        self,
        *,
        repo_root: str | Path | None = None,
        data_dir: str | Path | None = None,
        verify_provenance: bool = True,
        verify_polygon_files: bool = False,
    ) -> None:
        if repo_root is not None:
            self.repo_root = Path(repo_root).expanduser().resolve()
        elif data_dir is None or verify_polygon_files:
            self.repo_root = _repo_root_from_file()
        else:
            self.repo_root = None

        self.data_dir = (
            Path(data_dir).expanduser().resolve()
            if data_dir is not None
            else self.repo_root / "data" / "processed" / "c4" / "environment"
        )

        frame = _read_csv(self.data_dir / FEATURE_FILENAME)
        _check_ids(frame, FEATURE_FILENAME)

        expected = {"station_id", *FEATURE_COLUMNS}
        if set(frame.columns) != expected:
            missing = sorted(expected - set(frame.columns))
            unexpected = sorted(set(frame.columns) - expected)
            raise EnvironmentDataError(
                f"Feature CSV schema changed. Missing={missing}; unexpected={unexpected}"
            )

        # Numeric coercion is only for validation; non-numeric strings are errors.
        for name in FEATURE_COLUMNS:
            try:
                frame[name] = pd.to_numeric(frame[name], errors="raise")
            except (ValueError, TypeError) as exc:
                raise EnvironmentDataError(f"Non-numeric feature {name}") from exc
        values = frame.loc[:, FEATURE_COLUMNS].to_numpy(dtype=np.float64)
        if not np.isfinite(values).all():
            row, col = np.argwhere(~np.isfinite(values))[0]
            raise EnvironmentDataError(
                f"Invalid/missing value: {frame.iloc[row]['station_id']}, {FEATURE_COLUMNS[col]}"
            )
        for name in FRACTION_COLUMNS:
            if not frame[name].between(0, 1).all():
                raise EnvironmentDataError(f"Fraction outside [0,1]: {name}")
        if not frame["env_log1p_area_km2"].gt(0).all():
            raise EnvironmentDataError("Catchment log1p(area km2) must be positive")
        if not frame["env_mean_slope_deg"].between(0, 90).all():
            raise EnvironmentDataError("Mean slope must be within [0,90] degrees")
        if not frame["env_hydrorivers_density_km_per_km2"].ge(0).all():
            raise EnvironmentDataError("River length density cannot be negative")

        frame = frame.set_index("station_id").sort_index()
        self._frame = frame.loc[:, FEATURE_COLUMNS]
        self.manifest: dict | None = None

        if verify_provenance:
            qa = _read_csv(self.data_dir / QA_FILENAME)
            _check_ids(qa, QA_FILENAME)
            qa_ids = set(qa["station_id"].tolist())
            feature_ids = set(self._frame.index.tolist())
            if qa_ids != feature_ids:
                raise EnvironmentDataError(
                    f"QA/feature station IDs differ. "
                    f"Only in QA={sorted(qa_ids - feature_ids)}, "
                    f"only in features={sorted(feature_ids - qa_ids)}"
                )
            if "polygon_sha256" not in qa or "polygon_repo_path" not in qa:
                raise EnvironmentDataError("QA table missing polygon provenance fields")
            manifest_path = self.data_dir / MANIFEST_FILENAME
            if not manifest_path.is_file():
                raise FileNotFoundError(f"Missing Notebook 05 manifest: {manifest_path}")
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            if manifest.get("feature_order") != list(FEATURE_COLUMNS):
                raise EnvironmentDataError("Manifest feature_order differs from loader's nine-feature contract")
            if manifest.get("station_count") != EXPECTED_STATIONS:
                raise EnvironmentDataError("Manifest station_count is not 40")
            if manifest.get("feature_version") != EXPECTED_VERSION:
                raise EnvironmentDataError(
                    f"Unexpected environment extraction version: {manifest.get('feature_version')!r}"
                )
            hashes = manifest.get("station_polygon_sha256", {})
            if set(hashes) != feature_ids:
                raise EnvironmentDataError("Manifest polygon-hash station IDs do not match features")
            fingerprints = manifest.get("source_fingerprints", {})
            if set(fingerprints) != feature_ids:
                raise EnvironmentDataError("Manifest source fingerprints are incomplete")

            for row in qa.itertuples(index=False):
                sid = str(row.station_id)
                if str(row.polygon_sha256) != hashes[sid]:
                    raise EnvironmentDataError(f"Polygon hash mismatch between QA and manifest: {sid}")
                if verify_polygon_files:
                    if self.repo_root is None:
                        raise EnvironmentDataError("repo_root required to verify source polygons")
                    rel = str(row.polygon_repo_path).replace("\\", "/")
                    if not rel.startswith("shared/spatial/catchments/"):
                        raise EnvironmentDataError(f"Unexpected polygon path for {sid}: {rel}")
                    polygon_path = (self.repo_root / rel).resolve()
                    if not polygon_path.is_relative_to(self.repo_root):
                        raise EnvironmentDataError(f"Polygon path escapes repository: {sid}")
                    if not polygon_path.is_file():
                        raise FileNotFoundError(f"Missing polygon for {sid}: {polygon_path}")
                    if _sha256(polygon_path) != hashes[sid]:
                        raise EnvironmentDataError(f"Source polygon changed since extraction: {sid}")
            self.manifest = manifest

    @property
    def feature_names(self) -> tuple[str, ...]:
        return FEATURE_COLUMNS

    @property
    def station_count(self) -> int:
        return len(self._frame)

    def table(self) -> pd.DataFrame:
        """A fresh copy of the 40-row table, with station_id as a column."""
        return self._frame.reset_index().copy()

    def get_vector(self, station_id: str) -> np.ndarray:
        """Return one [9] float32 vector for a canonical station_id."""
        sid = str(station_id)
        if sid not in self._frame.index:
            raise KeyError(f"Unknown environment station_id={sid!r}; use canonical Notebook 01 station_id")
        return self._frame.loc[sid, list(FEATURE_COLUMNS)].to_numpy(dtype=np.float32, copy=True)

    def get_batch(self, station_ids: Iterable[str]) -> np.ndarray:
        """Return [N,9] float32 vectors in the exact input order (duplicates allowed)."""
        ids = [str(sid) for sid in station_ids]
        unknown = sorted(set(ids) - set(self._frame.index))
        if unknown:
            raise KeyError(f"Unknown environmental station IDs: {unknown}")
        result = self._frame.loc[ids, list(FEATURE_COLUMNS)].to_numpy(dtype=np.float32, copy=True)
        assert result.shape == (len(ids), len(FEATURE_COLUMNS))
        return result

    def for_station_days(self, records: pd.DataFrame) -> np.ndarray:
        """Align to a station-day manifest *without* reading labels/targets.

        Returns [len(records), 9] in the same row order. Repeated stations reuse
        the same static features; neither dates nor observed water levels are used.
        """
        if "station_id" not in records:
            raise EnvironmentDataError("Station-day manifest must have station_id")
        if records["station_id"].isna().any():
            raise EnvironmentDataError("Station-day manifest contains missing station_id")
        return self.get_batch(records["station_id"].tolist())


__all__ = ["FEATURE_COLUMNS", "EnvironmentDataError", "EnvironmentFeatureLoader"]
